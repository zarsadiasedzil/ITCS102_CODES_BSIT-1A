#Operation

# + - addition
# * - multiplication
# - - subtraction
# / - division
# // - floor division
# ** - exponentation
# % - modulus

#variable
a = 11
b = 5

#addition
sum = a + b
print("the sum of",a,"and",b,"is equivalent to",sum)

#multiplication
value = a * b
print("the value of",a,"and",b,"when multiply is",value)

#subtraction
difference = a - b
print("the sum of",a,"and",b,"is difference of",difference)

#division
qoutient = a / b
print("the qoutient of",a,"and",b,"is",qoutient)


# floor division
print("the integer division of",a,"and",b,"is",a//b)

# exponentation
print("the raised to the power of",a,"and",b,"is",a**b)

#modulus
print("the remainder of",a,"and",b,"is",a%b)